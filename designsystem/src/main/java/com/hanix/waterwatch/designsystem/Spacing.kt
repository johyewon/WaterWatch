package com.hanix.waterwatch.designsystem

import androidx.compose.ui.unit.dp

/*
 * 여백·간격 단계. 디자인 가이드가 아직 없어서 디자인 프로토타입과 지금 화면에서 반복해 쓰는 값을 모았다.
 * 가이드가 나오면 이 값만 바꾼다.
 */
object Spacing {

    /** 아이콘과 글자처럼 붙어 있는 요소 사이 */
    val Small = 8.dp

    /** 버튼·문구처럼 나란히 놓인 요소 사이 */
    val Medium = 12.dp

    /** 화면 위에 뜨는 카드(토스트)의 양옆 */
    val Large = 20.dp

    /** 화면 가장자리 안쪽 */
    val XLarge = 24.dp
}
